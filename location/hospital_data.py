# ============================================================
# GET STATES
# ============================================================

def get_states():

    return sorted(
        list(
            set(
                hospital["state"]
                for hospital in HOSPITALS
            )
        )
    )


# ============================================================
# GET CITIES
# ============================================================

def get_cities(state):

    return sorted(
        list(
            set(
                hospital["city"]
                for hospital in HOSPITALS
                if hospital["state"] == state
            )
        )
    )


# ============================================================
# GET AREAS
# ============================================================

def get_areas(state, city):

    return sorted(
        list(
            set(
                hospital["area"]
                for hospital in HOSPITALS
                if hospital["state"] == state
                and hospital["city"] == city
            )
        )
    )


# ============================================================
# GET HOSPITALS
# ============================================================

def get_hospitals(
    state,
    city,
    area=None
):

    hospitals = [

        hospital

        for hospital in HOSPITALS

        if hospital["state"] == state

        and hospital["city"] == city

    ]


    if area is not None and area != "All Areas":

        hospitals = [

            hospital

            for hospital in hospitals

            if hospital["area"] == area

        ]


    return hospitals