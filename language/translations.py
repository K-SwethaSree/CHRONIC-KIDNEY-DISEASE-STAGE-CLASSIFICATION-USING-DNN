def get_translation(language, key):

    if language not in TRANSLATIONS:
        language = "English"

    return TRANSLATIONS[language].get(
        key,
        TRANSLATIONS["English"].get(
            key,
            key
        )
    )


def get_recommendation_translation(language, text):

    if language not in RECOMMENDATIONS:
        language = "English"

    # Exact recommendation translation
    if text in RECOMMENDATIONS[language]:

        return RECOMMENDATIONS[language][text]

    # --------------------------------------------------------
    # Dynamic allergy recommendation
    # --------------------------------------------------------

    allergy_prefix = (
        "Avoid foods that contain your reported allergens:"
    )

    if text.startswith(allergy_prefix):

        allergens = text[len(allergy_prefix):].strip()

        if allergens.endswith("."):
            allergens = allergens[:-1]

        if language == "Telugu":

            return (
                "మీరు పేర్కొన్న అలెర్జీ కలిగించే ఆహారాలను "
                "నివారించండి: "
                + allergens
                + "."
            )

        if language == "Hindi":

            return (
                "आपके द्वारा बताए गए एलर्जी वाले खाद्य पदार्थों "
                "से बचें: "
                + allergens
                + "।"
            )

        return text

    # --------------------------------------------------------
    # Unknown recommendation
    # --------------------------------------------------------

    return RECOMMENDATIONS["English"].get(
        text,
        text
    )